function export_focus_bank(reference_root, python_exe)
% Explicit regeneration only. Normal Vitis builds use checked-in C tables.
this_dir=fileparts(mfilename('fullpath'));
root=fileparts(fileparts(this_dir));
if nargin<1, reference_root='D:/MyProjects/py_prj/ultrasound_dev_kit'; end
if nargin<2, python_exe='C:/Users/sunbaolin/miniconda3/envs/esp32c61/python.exe'; end
addpath(fullfile(reference_root,'tools','para_cal'));
addpath(fullfile(reference_root,'tools','para_cal','scripts'));
stage=tempname(fullfile(root,'build'));mkdir(stage);
output=fullfile(stage,'focus_bank_data.c');
for depth=20:10:170
    words=para_transmit_delay([],false,depth/1000);
    assert(isa(words,'uint32') && numel(words)==16384);
    declaration=sprintf('const uint32_t focus_delay_%03dmm[FOCUS_WORDS]',depth);
    preamble='';if depth==20, preamble=sprintf('/* Generated by MATLAB. Do not edit. */\n#include "focus_bank.h"\n');end
    write_C_array_file(output,declaration,words,8,8,sprintf('\t'),preamble,false,depth~=20);
    fid=fopen(fullfile(stage,sprintf('%d.bin',depth)),'w','ieee-le');assert(fid>=0);
    cleanup=onCleanup(@() fclose(fid));assert(fwrite(fid,words,'uint32')==16384);clear cleanup;
end
command=sprintf('"%s" "%s" --stage "%s" --reference "%s"',python_exe,fullfile(this_dir,'finalize_focus_bank.py'),stage,reference_root);
[status,text]=system(command);fprintf('%s',text);assert(status==0,'Focus export validation failed; installed bank unchanged.');
fprintf('Focus bank exported. Stage retained: %s\n',stage);
end
