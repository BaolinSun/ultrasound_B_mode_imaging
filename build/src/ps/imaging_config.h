#ifndef __IMAGING_CONFIG_H
#define __IMAGING_CONFIG_H

#define ADC_SAMPLE_NUM        6144U

#define RAW_BYTES_PER_SAMPLE  64U
#define RAW_FRAME_BYTES       (ADC_SAMPLE_NUM * RAW_BYTES_PER_SAMPLE)

#define BF_LINE_NUM           64U
#define BF_SAMPLE_NUM         ADC_SAMPLE_NUM
#define BF_LINE_HEADER_WORDS  8U
#define BF_BYTES_PER_SAMPLE   2U
#define BF_LINE_WORDS         (BF_LINE_HEADER_WORDS + BF_SAMPLE_NUM)
#define BF_LINE_BYTES         (BF_LINE_WORDS * BF_BYTES_PER_SAMPLE)
#define BF_FRAME_BYTES        (BF_LINE_NUM * BF_LINE_BYTES)

#define DDR_RING_BASE_ADDR    0x20000000U
#define DDR_RING_BYTES        (1024U * 1000U)

#define USB_TRANSFER_PACKET_BYTES 1024U
#define USB_TRANSFER_WINDOW_BYTES DDR_RING_BYTES
#define USB_TOTAL_PACKET          ((USB_TRANSFER_WINDOW_BYTES + USB_TRANSFER_PACKET_BYTES - 1U) / USB_TRANSFER_PACKET_BYTES)

#endif
