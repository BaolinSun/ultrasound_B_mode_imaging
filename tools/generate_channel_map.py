#!/usr/bin/env python3
"""Validate the probe wiring table and generate the RX ingress reorder RTL."""

from __future__ import annotations

import argparse
import csv
import sys
from dataclasses import dataclass
from pathlib import Path


PROJECT_ROOT = Path(__file__).resolve().parents[1]
MAP_PATH = PROJECT_ROOT / "tools" / "configs" / "probe_channel_map.csv"
RTL_PATH = (
    PROJECT_ROOT
    / "build"
    / "src"
    / "imports"
    / "sources"
    / "rx_channel_reorder.sv"
)
EXPECTED_COLUMNS = (
    "physical_element",
    "tx_global_channel",
    "tx_device",
    "tx_local_channel",
    "synthetic_aperture",
    "afe_channel",
)


@dataclass(frozen=True)
class ChannelMapRow:
    physical_element: int
    tx_global_channel: int
    tx_device: int
    tx_local_channel: int
    synthetic_aperture: int
    afe_channel: int


def load_and_validate_map(path: Path = MAP_PATH) -> list[ChannelMapRow]:
    with path.open(newline="", encoding="utf-8") as csv_file:
        reader = csv.DictReader(csv_file)
        if tuple(reader.fieldnames or ()) != EXPECTED_COLUMNS:
            raise ValueError(
                f"{path}: expected columns {EXPECTED_COLUMNS}, got {reader.fieldnames}"
            )
        rows = [
            ChannelMapRow(**{column: int(raw[column]) for column in EXPECTED_COLUMNS})
            for raw in reader
        ]

    if len(rows) != 64:
        raise ValueError(f"{path}: expected 64 rows, got {len(rows)}")

    physical_elements = [row.physical_element for row in rows]
    tx_channels = [row.tx_global_channel for row in rows]
    if physical_elements != list(range(1, 65)):
        raise ValueError("physical_element must be the ordered sequence 1..64")
    if sorted(tx_channels) != list(range(1, 65)):
        raise ValueError("tx_global_channel must be a bijection over 1..64")

    for row in rows:
        expected_tx_channel = (
            row.physical_element + 1
            if row.physical_element % 2 == 1
            else row.physical_element - 1
        )
        expected_device = (row.physical_element - 1) // 32 + 1
        expected_local_channel = (expected_tx_channel - 1) % 32 + 1
        expected_aperture = (row.physical_element - 1) // 32
        if row.tx_global_channel != expected_tx_channel:
            raise ValueError(
                f"element {row.physical_element}: expected TX channel "
                f"{expected_tx_channel}, got {row.tx_global_channel}"
            )
        if row.tx_device != expected_device:
            raise ValueError(
                f"element {row.physical_element}: expected TX device "
                f"{expected_device}, got {row.tx_device}"
            )
        if row.tx_local_channel != expected_local_channel:
            raise ValueError(
                f"element {row.physical_element}: expected local TX channel "
                f"{expected_local_channel}, got {row.tx_local_channel}"
            )
        if row.synthetic_aperture != expected_aperture:
            raise ValueError(
                f"element {row.physical_element}: expected aperture "
                f"{expected_aperture}, got {row.synthetic_aperture}"
            )
        if row.afe_channel != expected_local_channel:
            raise ValueError(
                f"element {row.physical_element}: AFE channel must match the "
                f"TX local channel {expected_local_channel}"
            )

    for aperture in (0, 1):
        afe_channels = [
            row.afe_channel for row in rows if row.synthetic_aperture == aperture
        ]
        if sorted(afe_channels) != list(range(1, 33)):
            raise ValueError(
                f"synthetic aperture {aperture}: AFE channels are not a 1..32 bijection"
            )

    return rows


def render_rx_rtl(rows: list[ChannelMapRow]) -> str:
    local_rows = [row for row in rows if row.synthetic_aperture == 0]
    lines = [
        "`timescale 1ns/1ps",
        "",
        "// AUTO-GENERATED by tools/generate_channel_map.py.",
        "// Source of truth: tools/configs/probe_channel_map.csv",
        "// AFE raw channels are reordered here; all downstream logic uses physical order.",
        "module rx_channel_reorder",
        "(",
        "\tinput  logic         raw_valid,",
        "\tinput  logic [511:0] raw_data,",
        "\toutput logic         physical_valid,",
        "\toutput logic [511:0] physical_data",
        ");",
        "",
        "assign physical_valid = raw_valid;",
        "",
    ]
    for physical_slot, row in enumerate(local_rows):
        raw_lsb = (row.afe_channel - 1) * 16
        physical_lsb = physical_slot * 16
        lines.append(
            f"assign physical_data[{physical_lsb} +: 16] = "
            f"raw_data[{raw_lsb} +: 16];  "
            f"// Physical slot {physical_slot + 1} <- AFE CH{row.afe_channel}"
        )
    lines.extend(["", "endmodule", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--write", action="store_true", help="write the generated RTL file"
    )
    mode.add_argument(
        "--check", action="store_true", help="check that generated RTL is current"
    )
    args = parser.parse_args()

    try:
        rows = load_and_validate_map()
        expected_rtl = render_rx_rtl(rows)
        if args.write:
            RTL_PATH.parent.mkdir(parents=True, exist_ok=True)
            RTL_PATH.write_text(expected_rtl, encoding="utf-8", newline="\n")
            print(f"Wrote {RTL_PATH.relative_to(PROJECT_ROOT)}")
        else:
            actual_rtl = RTL_PATH.read_text(encoding="utf-8")
            if actual_rtl.replace("\r\n", "\n") != expected_rtl:
                raise ValueError(
                    f"{RTL_PATH}: generated RTL is stale; run "
                    "python tools/generate_channel_map.py --write"
                )
            print("Channel map and generated RX RTL are consistent")
    except (OSError, ValueError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

