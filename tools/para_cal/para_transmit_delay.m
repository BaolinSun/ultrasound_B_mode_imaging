function delay_fpga = para_transmit_delay(output_dir, write_json)
%PARA_TRANSMIT_DELAY Calculate physical delays and pack TX hardware words.
if nargin < 1 || isempty(output_dir)
    output_dir = default_config_dir();
end
if nargin < 2
    write_json = true;
end

pitch       = 0.3e-3;
element_num = 64;
c           = 1540;
F           = 80e-3;
nxmits      = 64;

idx = (0:element_num-1)';
probe_geometry_vectors = zeros(element_num, 3);
probe_geometry_vectors(:, 1) = (idx - (element_num-1) / 2) * pitch;

angles = linspace(-45, 45, nxmits);
theta = deg2rad(angles);

xx = F * sin(theta);
yy = zeros(1, nxmits);
zz = F * cos(theta);

delay = zeros(nxmits, element_num);
for i = 1:nxmits
    delay(i, :) = cal_phased_array_transmit_delay( ...
        probe_geometry_vectors, [xx(i), yy(i), zz(i)], F, c);
end

physical_delay = int32(floor(delay / 10e-9));
channel_map = load_probe_channel_map();
delay_fpga = pack_tx7332_delay_words(physical_delay, channel_map);

if write_json
    write_bram_json( ...
        output_dir, ...
        'delay_profile_default.json', ...
        'Transmit delay profile generated by para_transmit_delay.m', ...
        {'delay_profile'}, ...
        {delay_fpga});
end
end

function delay_vec = cal_phased_array_transmit_delay(probe_geometry_vectors, focus_point, F, c)
fp = focus_point(:)';
diff = probe_geometry_vectors - fp;
L = sqrt(sum(diff .^ 2, 2));
delay_vec = 6e-6 - (L - F) / c;
% delay_vec = (max(L) - L) / c;
end
